function systemLocale(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale;
  } catch {
    return "";
  }
}

/** Picked once at startup from the phone's language; anything other than Polish gets English. */
export const t: Messages = systemLocale().toLowerCase().startsWith("pl") ? pl : en;
